/**
 * Multi-perspective persona discovery.
 *
 * Port of `backend/src/lmeditor/discovery/perspective.py`.
 *
 * A perspective here is not a job title with the topic pasted into it. The
 * archetype table supplies the *stance* -- the expert, the skeptic, the
 * practitioner, the regulator, the analyst, the expositor -- while the
 * substance of every persona (its description, its focus areas, its guiding
 * questions and its key inquiries) is taken from the material the persona is
 * supposed to interrogate.
 *
 * When a language model is configured and [useModel] is enabled, the persona
 * content is generated by the model, which is given the source context. When
 * no model is available, the same content is derived deterministically from
 * the context by the lexicon in [SourceAnalysis].
 */
class PerspectiveGenerator(
    private val useModel: Boolean = false,
    private val model: PerspectiveModel? = null,
) {
