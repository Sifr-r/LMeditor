        /** A JSON array fenced in a markdown code block. */
        private val FENCED_JSON_RE: Regex =
            Regex("```(?:json)?\\s*(\\[.*?\\])\\s*```", setOf(RegexOption.DOT_MATCHES_ALL))
    }

    /**
     * Validate topic and count boundaries strictly.
     *
     * @return the sanitized topic.
     * @throws ValidationError if a boundary is breached.
     */
    fun validateInputs(topic: String, numPerspectives: Int): String {
        val cleanedTopic = SourceAnalysis.strip(topic)
        if (cleanedTopic.isEmpty()) {
            throw ValidationError(
                "Topic cannot be empty or whitespace.",
                field = "topic",
                value = topic,
            )
        }
        val topicLength = CodePoints.length(cleanedTopic)
        if (topicLength < 3 || topicLength > 1000) {
            throw ValidationError(
                "Topic length must be between 3 and 1000 characters, got $topicLength",
                field = "topic",
                value = cleanedTopic,
            )
        }

        if (numPerspectives < 1 || numPerspectives > 10) {
            throw ValidationError(
                "num_perspectives must be between 1 and 10, got $numPerspectives",
                field = "num_perspectives",
                value = numPerspectives,
            )
        }

        return cleanedTopic
    }

    /**
     * Generate diverse investigative perspectives for a topic.
     *
     * @param topic the research subject or thesis.
     * @param context optional domain context or background excerpts. The
     *   personas are grounded in this material.
     * @param numPerspectives the count of personas to generate (1 to 10).
     * @param maxPerspectives overrides [numPerspectives] when supplied.
     * @throws ValidationError if the inputs violate a boundary rule.
     * @throws PerspectiveGenerationError if persona synthesis fails.
     */
    fun generatePerspectives(
        topic: String,
        context: String? = null,
        numPerspectives: Int = 4,
        maxPerspectives: Int? = null,
    ): List<Perspective> {
        val targetCount = maxPerspectives ?: numPerspectives
        val cleanTopic = validateInputs(topic, targetCount)
        val cleanContext = SourceAnalysis.strip(context ?: "")

        if (useModel) {
            return generatePerspectivesWithModel(cleanTopic, cleanContext, targetCount)
        }

        return generateHeuristicPerspectives(cleanTopic, cleanContext, targetCount)
    }

    // ----------------------------------------------------------------------
    // Language-model path
    // ----------------------------------------------------------------------

    /**
     * Generate the personas with the configured language model.
     *
     * A model that is not supplied is a configuration failure, not a
     * downgrade: [LMNotConfiguredError] is raised rather than quietly
     * producing a generic persona list. A model that answers with something
     * unusable is a real failure too, and raises.
     */
    private fun generatePerspectivesWithModel(
        topic: String,
        context: String,
        count: Int,
    ): List<Perspective> {
        val lm = model ?: throw LMNotConfiguredError("perspective discovery")

        val raw = try {
            lm.proposePerspectives(topic, context.ifEmpty { "General domain literature" }, count)
        } catch (exc: Exception) {
            throw PerspectiveGenerationError(
                "Language model failed to generate perspectives: $exc",
                details = mapOf("topic" to topic, "num_perspectives" to count),
            )
        }

        val parsed = parseModelOutput(raw, topic, count)
        if (parsed.isEmpty()) {
            throw PerspectiveGenerationError(
                "Language model returned no usable perspective payload.",
                details = mapOf("topic" to topic, "raw_output" to raw.take(500)),
            )
        }
        return parsed
    }

    /** Safely parse and validate the structured JSON the model returned. */
    private fun parseModelOutput(
        rawJson: String,
        topic: String,
        targetCount: Int,
    ): List<Perspective> {
        var cleaned = SourceAnalysis.strip(rawJson)
        if (cleaned.contains("```")) {
            val fenced = FENCED_JSON_RE.find(cleaned)
            if (fenced != null) cleaned = fenced.groupValues[1]
        }

        val data = try {
            Json.parse(cleaned)
        } catch (exc: Exception) {
            return emptyList()
        }
        if (data !is List<*>) return emptyList()

        val perspectives = mutableListOf<Perspective>()
        for ((index, item) in data.take(targetCount).withIndex()) {
            if (item !is Map<*, *>) continue

            val role = roleOf(item["role"])
            val pid = item["id"]?.toString()?.takeIf { it.isNotEmpty() }
                ?: "persp_${role.wire}_${index + 1}"
            val title = item["title"]?.toString()?.takeIf { it.isNotEmpty() }
                ?: item["name"]?.toString()?.takeIf { it.isNotEmpty() }
                ?: "${capitalize(role.wire)} Specialist"
            val desc = item["description"]?.toString() ?: "Expert investigating $topic"
            val focus = item["focus_areas"].asStringList()
                .ifEmpty { listOf("Core mechanics of $topic") }
            val questions = item["guiding_questions"].asStringList()
                .ifEmpty { listOf("What are the main dynamics of $topic?") }
            val inquiries = item["key_inquiries"].asStringList().ifEmpty { questions }

            perspectives.add(
                Perspective(
                    perspectiveId = pid,
                    id = pid,
                    role = role,
                    title = title,
                    name = title,
                    description = desc,
                    domain = topic,
                    focusAreas = focus,
                    guidingQuestions = questions,
                    keyInquiries = inquiries,
                ),
            )
        }

        if (perspectives.size >= targetCount) return perspectives.take(targetCount)
        return emptyList()
    }

    // ----------------------------------------------------------------------
    // Deterministic path
    // ----------------------------------------------------------------------

    /** Produce deterministic perspectives grounded in the supplied context. */
    private fun generateHeuristicPerspectives(
        topic: String,
        context: String,
        count: Int,
    ): List<Perspective> {
        val perspectives = mutableListOf<Perspective>()
        val archetypes = ROLE_ARCHETYPES

        val terms = SourceAnalysis
            .salientTerms(context, limit = 10)
            .filter { it !in SourceAnalysis.GENERIC_TERMS }
        val findings = SourceAnalysis.extractFindings(context, limit = 8)

        for (index in 0 until count) {
            val archetype = archetypes[index % archetypes.size]

            val perspId = "persp_${archetype.role.wire}_${index + 1}"
            val title = "${archetype.name} on $topic"

            // Every persona anchors on the terms of the material it will read
            // and on the findings that material actually states.
            val personaTerms = rotate(terms, index, limit = 4)
            val personaFindings = rotate(findings, index, limit = 3)

            val description = buildDescription(
                baseDesc = archetype.description,
                topic = topic,
                terms = personaTerms,
                findings = personaFindings,
                context = context,
            )
            val focusAreas = buildFocusAreas(
                baseFocus = archetype.focusAreas,
                topic = topic,
                terms = personaTerms,
                findings = personaFindings,
            )
            val guidingQuestions = buildGuidingQuestions(
                baseQuestions = archetype.guidingQuestions,
                topic = topic,
                terms = personaTerms,
                findings = personaFindings,
            )
            val keyInquiries = buildKeyInquiries(
                role = archetype.role,
                topic = topic,
                terms = personaTerms,
                findings = personaFindings,
            )

            perspectives.add(
                Perspective(
                    perspectiveId = perspId,
                    id = perspId,
                    role = archetype.role,
                    title = title,
                    name = title,
                    description = description,
                    domain = topic,
                    focusAreas = focusAreas,
                    promptDirectives = listOf(
                        "Adopt the stance of a ${archetype.role.wire}.",
                        "Interrogate all claims about '$topic' through rigorous evidence.",
                        "Always mandate source passage attribution.",
                    ) + if (personaTerms.isNotEmpty()) {
                        listOf("Anchor every answer in the supplied material on ${personaTerms[0]}.")
                    } else {
                        emptyList()
                    },
                    guidingQuestions = guidingQuestions,
                    keyInquiries = keyInquiries,
                ),
            )
        }

        return perspectives
    }

    /**
     * Take [limit] items from [items], starting at [offset].
     *
     * Rotating gives each archetype a different slice of the material, so
     * two personas do not interrogate the same passage.
     */
    private fun rotate(items: List<String>, offset: Int, limit: Int): List<String> {
        if (items.isEmpty()) return emptyList()
        val count = items.size
        return (0 until minOf(limit, count)).map { items[(offset + it) % count] }
    }

    /** Describe the persona in terms of the material it reads. */
    private fun buildDescription(
        baseDesc: String,
        topic: String,
        terms: List<String>,
        findings: List<String>,
        context: String,
    ): String {
        if (SourceAnalysis.strip(context).isEmpty()) {
            return "$baseDesc Specializing in analyzing '$topic' with uncompromising domain depth."
        }

        val parts = mutableListOf(
            "$baseDesc Specializing in analyzing '$topic' with uncompromising domain depth.",
        )
        if (terms.isNotEmpty()) {
            parts.add(
                "This persona reads the supplied material through ${terms.take(3).joinToString(", ")}, " +
                    "and treats what that material reports as the primary evidence.",
            )
        }
        if (findings.isNotEmpty()) {
            parts.add("Its point of departure is the reported finding: \"${findings[0]}\"")
        }
        return parts.joinToString(" ")
    }

    /** Ground each archetype focus area in a term of the source material. */
    private fun buildFocusAreas(
        baseFocus: List<String>,
        topic: String,
        terms: List<String>,
        findings: List<String>,
    ): List<String> {
        val focusAreas = mutableListOf<String>()
        for ((index, focus) in baseFocus.withIndex()) {
            if (terms.isNotEmpty()) {
                val anchor = terms[index % terms.size]
                focusAreas.add("$focus, read against the evidence on $anchor")
            } else {
                focusAreas.add("$focus in the context of $topic")
            }
        }

        for (finding in findings.take(2)) {
            focusAreas.add("Interrogating the claim that $finding")
        }

        return focusAreas
    }

    /** Ground each archetype question in the source material. */
    private fun buildGuidingQuestions(
        baseQuestions: List<String>,
        topic: String,
        terms: List<String>,
        findings: List<String>,
    ): List<String> {
        val questions = mutableListOf<String>()
        for ((index, question) in baseQuestions.withIndex()) {
            val framed = if (question.contains("{topic}")) {
                question.replace("{topic}", topic)
            } else {
                question
            }
            if (terms.isNotEmpty()) {
                val anchor = terms[index % terms.size]
                questions.add("$framed Ground the answer in what the source says about $anchor.")
            } else {
                questions.add("$framed ($topic)")
            }
        }

        for (finding in findings.take(2)) {
            questions.add(
                "The source states: \"$finding\" — does this support or undercut the claim, " +
                    "and by what mechanism?",
            )
        }

        return questions
    }

    /** The role-specific inquiries, each anchored in the source material. */
    private fun buildKeyInquiries(
        role: PerspectiveRole,
        topic: String,
        terms: List<String>,
        findings: List<String>,
    ): List<String> {
        val inquiries = mutableListOf<String>()
        if (terms.isNotEmpty()) {
            inquiries.add(
                "Which passage about ${terms[0]} most constrains the ${role.wire} reading of $topic?",
            )
        }
        if (terms.size > 1) {
            inquiries.add(
                "How do ${terms[1]} and ${terms[0]} interact in the material, and what follows for $topic?",
            )
        }
        if (findings.isNotEmpty()) {
            inquiries.add(
                "What evidence would falsify the reported claim that ${asClause(findings[0])}?",
            )
        }
        inquiries.add("What does the material not settle about $topic, and what would settle it?")
        return inquiries
    }

    /**
     * [finding] as a clause that can sit inside another sentence.
     *
     * A finding is a whole sentence, so it carries its own terminal
     * punctuation. Interpolating one verbatim into the middle of a question
     * would otherwise produce a double mark ("...within days.?").
     */
    private fun asClause(finding: String): String = finding.trimEnd(' ', '.', ';', ':', ',')

    /** The role a model answer names, falling back to the domain expert. */
    private fun roleOf(raw: Any?): PerspectiveRole {
        val wire = raw?.toString() ?: return PerspectiveRole.DOMAIN_EXPERT
        return try {
            PerspectiveRole.fromWire(wire)
        } catch (exc: ValidationError) {
            PerspectiveRole.DOMAIN_EXPERT
        }
    }

    /** Python's `str.capitalize()`: first character up, the rest down. */
    private fun capitalize(text: String): String =
        if (text.isEmpty()) text
        else text.substring(0, 1).uppercase() + text.substring(1).lowercase()

    /** A JSON value read as a list of strings, empty when it is not one. */
    private fun Any?.asStringList(): List<String> =
        (this as? List<*>)?.mapNotNull { it?.toString() } ?: emptyList()
}
