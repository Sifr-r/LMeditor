"""Language-model configuration for LMeditor.

LMeditor is a *writing* harness: every manuscript it produces is generated by
a language model. This module is the single place that decides **which** model
is used and **how** it is reached.

Configuration is environment-driven so the same build works against a hosted
provider or a local model server:

=====================  ====================================================
Environment variable  Meaning
=====================  ====================================================
``LMEDITOR_LM_PROVIDER``  ``openai`` | ``anthropic`` | ``ollama`` |
                          ``gemini`` | ``openai-compatible`` | ``codex``
``LMEDITOR_LM_MODEL``     Model identifier, provider-qualified or bare
``LMEDITOR_LM_API_KEY``   API key (not needed for local servers)
``LMEDITOR_LM_BASE_URL``  Base URL for a local / OpenAI-compatible server
``LMEDITOR_LM_TEMPERATURE``  Sampling temperature (default ``0.2``)
``LMEDITOR_LM_MAX_TOKENS``    Generation cap (default ``4096``)
=====================  ====================================================

Example (local, no network egress)::

    LMEDITOR_LM_PROVIDER=ollama
    LMEDITOR_LM_MODEL=llama3.1
    LMEDITOR_LM_BASE_URL=http://127.0.0.1:11434

Example (hosted)::

    LMEDITOR_LM_PROVIDER=openai
    LMEDITOR_LM_MODEL=gpt-4o-mini
    LMEDITOR_LM_API_KEY=sk-...
"""

from __future__ import annotations

import os
from enum import Enum
from typing import Any, Optional

from pydantic import BaseModel, ConfigDict, Field, field_validator

from lmeditor.core.exceptions import LMNotConfiguredError


class LMProvider(str, Enum):
    """Supported language-model backends."""

    OPENAI = "openai"
    ANTHROPIC = "anthropic"
    OLLAMA = "ollama"
    GEMINI = "gemini"
    OPENAI_COMPATIBLE = "openai-compatible"
    #: The installed CLI owns authentication. A model of ``default`` uses its
    #: built-in model default; the adapter ignores unrelated user config.
    CODEX = "codex"
    #: A deterministic, grounded drafter for offline use. It quotes the source
    #: passages it is given and cites their real chunk ids; it is not a
    #: language model and reports itself as ``stub`` everywhere it is named.
    STUB = "stub"

    @property
    def requires_api_key(self) -> bool:
        """Whether this provider needs an API key to be usable."""
        return self in (LMProvider.OPENAI, LMProvider.ANTHROPIC, LMProvider.GEMINI)

    @property
    def default_model(self) -> str:
        """Sensible default model for the provider."""
        return {
            LMProvider.OPENAI: "gpt-4o-mini",
            LMProvider.ANTHROPIC: "claude-sonnet-4-5",
            LMProvider.OLLAMA: "llama3.1",
            LMProvider.GEMINI: "gemini-2.0-flash",
            LMProvider.OPENAI_COMPATIBLE: "local-model",
            LMProvider.CODEX: "default",
            LMProvider.STUB: "stub",
        }[self]

    @property
    def default_base_url(self) -> str:
        """Default base URL, when the provider has one."""
        return {
            LMProvider.OLLAMA: "http://127.0.0.1:11434",
        }.get(self, "")


_PROVIDER_ALIASES: dict[str, LMProvider] = {
    "openai": LMProvider.OPENAI,
    "azure": LMProvider.OPENAI,
    "openai-compatible": LMProvider.OPENAI_COMPATIBLE,
    "openai_compatible": LMProvider.OPENAI_COMPATIBLE,
    "local": LMProvider.OPENAI_COMPATIBLE,
    "lmstudio": LMProvider.OPENAI_COMPATIBLE,
    "vllm": LMProvider.OPENAI_COMPATIBLE,
    "anthropic": LMProvider.ANTHROPIC,
    "claude": LMProvider.ANTHROPIC,
    "ollama": LMProvider.OLLAMA,
    "gemini": LMProvider.GEMINI,
    "google": LMProvider.GEMINI,
    "codex": LMProvider.CODEX,
    "codex-cli": LMProvider.CODEX,
    "stub": LMProvider.STUB,
    "offline": LMProvider.STUB,
}


def parse_provider(raw: str) -> LMProvider:
    """Map a provider string onto :class:`LMProvider`.

    Raises:
        ValueError: if the string names no known provider.
    """
    key = raw.strip().lower()
    if key in _PROVIDER_ALIASES:
        return _PROVIDER_ALIASES[key]
    raise ValueError(
        f"Unknown LM provider '{raw}'. "
        f"Expected one of: {', '.join(sorted(p.value for p in LMProvider))}."
    )


class LMConfig(BaseModel):
    """Resolved language-model settings.

    An instance is *complete* when :meth:`validate_ready` succeeds: the
    provider is known, a model is named, and any required key is present.
    """

    model_config = ConfigDict(frozen=True, extra="forbid")

    provider: LMProvider = Field(description="Backend used to reach the model")
    model: str = Field(min_length=1, description="Model identifier")
    api_key: Optional[str] = Field(default=None, description="API key, when the provider needs one")
    base_url: Optional[str] = Field(default=None, description="Base URL for a local/compatible server")
    temperature: float = Field(default=0.2, ge=0.0, le=2.0, description="Sampling temperature")
    max_tokens: int = Field(default=4096, ge=1, description="Maximum tokens per generation")

    @field_validator("temperature")
    @classmethod
    def _round_temperature(cls, value: float) -> float:
        return round(float(value), 4)

    @property
    def dspy_model_string(self) -> str:
        """The provider-qualified model string DSPy/litellm expects."""
        if self.provider in (LMProvider.OPENAI_COMPATIBLE, LMProvider.STUB, LMProvider.CODEX):
            # Custom adapters consume bare names; Codex's "default" sentinel
            # uses the CLI's built-in default rather than naming a model.
            return self.model
        prefix = {
            LMProvider.OPENAI: "openai",
            LMProvider.ANTHROPIC: "anthropic",
            LMProvider.OLLAMA: "ollama",
            LMProvider.GEMINI: "gemini",
        }[self.provider]
        if self.model.startswith(f"{prefix}/"):
            return self.model
        return f"{prefix}/{self.model}"

    def validate_ready(self, operation: str = "generation") -> None:
        """Raise :class:`LMNotConfiguredError` unless this config is usable.

        Args:
            operation: name of the operation that needs the model, used in
                the error message.
        """
        if not self.model.strip():
            raise LMNotConfiguredError(operation)
        if self.provider is LMProvider.CODEX and (self.api_key or self.base_url):
            raise LMNotConfiguredError(
                operation,
                "Codex uses the installed CLI's saved authentication. Unset "
                "LMEDITOR_LM_API_KEY and LMEDITOR_LM_BASE_URL for provider 'codex'; "
                "sign in with 'codex login' instead.",
            )
        if self.provider.requires_api_key and not (self.api_key or "").strip():
            raise LMNotConfiguredError(
                operation,
                f"No language model is configured, so '{operation}' cannot run: provider "
                f"'{self.provider.value}' requires an API key but none was supplied. "
                "Set LMEDITOR_LM_API_KEY (or switch to a local provider such as "
                "LMEDITOR_LM_PROVIDER=ollama).",
            )

    @classmethod
    def from_env(cls, environ: Optional[dict[str, str]] = None) -> Optional["LMConfig"]:
        """Build a config from the environment.

        Returns:
            The resolved config, or ``None`` when no provider is configured —
            the caller decides whether that is fatal.
        """
        env = environ if environ is not None else dict(os.environ)
        raw_provider = (env.get("LMEDITOR_LM_PROVIDER") or "").strip()
        if not raw_provider:
            return None
        provider = parse_provider(raw_provider)
        model = (env.get("LMEDITOR_LM_MODEL") or "").strip() or provider.default_model
        api_key = (env.get("LMEDITOR_LM_API_KEY") or "").strip() or None
        base_url = (env.get("LMEDITOR_LM_BASE_URL") or "").strip() or (
            provider.default_base_url or None
        )
        raw_temperature = (env.get("LMEDITOR_LM_TEMPERATURE") or "").strip()
        raw_max_tokens = (env.get("LMEDITOR_LM_MAX_TOKENS") or "").strip()
        return cls(
            provider=provider,
            model=model,
            api_key=api_key,
            base_url=base_url,
            temperature=float(raw_temperature) if raw_temperature else 0.2,
            max_tokens=int(raw_max_tokens) if raw_max_tokens else 4096,
        )

    def describe(self) -> dict[str, Any]:
        """A redacted, log-safe description of this configuration."""
        return {
            "provider": self.provider.value,
            "model": self.model,
            "base_url": self.base_url,
            "temperature": self.temperature,
            "max_tokens": self.max_tokens,
            "api_key_present": bool((self.api_key or "").strip()),
        }


__all__ = ["LMProvider", "LMConfig", "parse_provider"]
