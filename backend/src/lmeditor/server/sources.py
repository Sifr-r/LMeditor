def _call(operation: str, action: Callable[[], _T]) -> _T:
    """Run a call across the seam, keeping the tier's refusals as they are.

    A tier that is not there is an infrastructure failure, not a bad input:
    it is never dressed up as one, and it is never answered from a Python copy
    of the rule.

    A failure of the tier's own is the same kind of failure: the reason may
    name the JVM, its class names and the stderr it died with, so it does
    not travel to the client. The client is told which operation the tier
    could not carry out, and the reason goes to the log.
    """
    try:
        return action()
    except BridgeUnavailableError:
        raise
    except LMeditorError:
        raise
    except Exception as exc:  # pragma: no cover - the tier's own failures
        logger.error("The Kotlin tier could not %s: %s", operation, exc, exc_info=exc)
        raise LMeditorError(f"the Kotlin tier could not {operation}") from exc


def _string_from_wire(wire: Mapping[str, Any], key: str) -> str:
    """Return a required string field of the wire form.

    Raises:
        ValidationError: The field is missing or is not a string.
    """
    value = wire.get(key)
    if not isinstance(value, str):
        raise ValidationError(
            f"the tier's stored source has no string '{key}'",
            field=key,
            value=value,
        )
    return value


def _kind_from_wire(value: Any) -> SourceKind:
    """Return the source kind of the wire form.

    Raises:
        ValidationError: The field is missing, is not a string, or names a
            kind this tier does not know.
    """
    if not isinstance(value, str):
        raise ValidationError(
            "the tier's stored source has no string 'kind'",
            field="kind",
            value=value,
        )
    try:
        return SourceKind(value)
    except ValueError as exc:
        raise ValidationError(
            f"the tier's stored source names an unknown kind '{value}'",
            field="kind",
            value=value,
        ) from exc


def _chunks_from_wire(value: Any) -> tuple[SourceChunk, ...]:
    """Return the chunks of the wire form.

    Raises:
        ValidationError: The field is neither absent nor a list.
    """
    if value is None:
        return ()
    if not isinstance(value, (list, tuple)):
        raise ValidationError(
            "the tier's stored source has no list 'chunks'",
            field="chunks",
            value=value,
        )
    return tuple(SourceChunk.model_validate(item) for item in value)


def _record_from_wire(value: Any) -> BibliographicRecord | None:
    """Return the bibliographic record of the wire form.

    Raises:
        ValidationError: The field is neither absent nor null.
    """
    if value is None:
        return None
    return BibliographicRecord.model_validate(value)


def _optional_int_from_wire(value: Any) -> int | None:
    """Return the byte size of the wire form.

    Raises:
        ValidationError: The field is neither absent, null, nor an integer.
    """
    if value is None:
        return None
    if isinstance(value, bool) or not isinstance(value, int):
        raise ValidationError(
            "the tier's stored source has no integer 'byte_size'",
            field="byte_size",
            value=value,
        )
    return value


def _string_list_from_wire(value: Any) -> list[str]:
    """Return the omissions of the wire form.

    Raises:
        ValidationError: The field is neither absent nor a list.
    """
    if value is None:
        return []
    if not isinstance(value, (list, tuple)):
        raise ValidationError(
            "the tier's stored source has no list 'omissions'",
            field="omissions",
            value=value,
        )
    return [str(item) for item in value]


def _wire_timestamp(value: datetime) -> str:
    """Return a timestamp in the wire spelling: an ISO-8601 instant in UTC.

    The tier holds an instant, so a timestamp crosses the seam as one, and
    this is the spelling the tier writes it in. A timestamp with no offset is
    read as UTC rather than as the machine's local time, because a timestamp
    without an offset has no other meaning.
    """
    moment = (
        value.replace(tzinfo=timezone.utc)
        if value.tzinfo is None
        else value.astimezone(timezone.utc)
    )
    return moment.isoformat().replace("+00:00", "Z")


def _instant_from_wire(value: Any) -> datetime:
    """Return the timestamp of the wire form.

    The tier writes an ISO-8601 string, which is what ``isoformat`` reads
    back.

    Raises:
        ValidationError: The field is missing, is not a string, or is not a
            timestamp.
    """
    if not isinstance(value, str):
        raise ValidationError(
            "the tier's stored source has no string 'added_at'",
            field="added_at",
            value=value,
        )
    try:
        return datetime.fromisoformat(value)
    except ValueError as exc:
        raise ValidationError(
            f"the tier's stored source has no timestamp 'added_at': {value!r}",
            field="added_at",
            value=value,
        ) from exc
