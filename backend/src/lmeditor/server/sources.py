"""Server-side source library.

Ingested sources used to exist only as the bytes the client happened to hold:
the desktop client uploaded a file, received chunks back, and then had to
POST those chunks to ``/documents/generate`` so the workflow could see them.
Nothing on the server remembered what had been ingested, so a second client,
a restarted app, or a document generated from the command line had no way to
reach the material it had just uploaded.

This module is the server's memory of ingested sources. It stores the chunks
and the resolved bibliographic record of every ingested artifact so a
document can be generated by referring to its sources by id.

The library itself is the Kotlin tier's: it is one registry in the long-lived
tier, and this module is the **door** to it. It keeps the Python API the rest
of the backend calls, and answers with the tier's answers. The implementation
it used to carry now lives in ``lmeditor._reference.server_sources``, frozen,
so the parity harness can still ask both sides the same question.

The rules are the tier's, and this module holds none of them:

* the cache rule -- memory eviction never removes an archived source;
* the ordering -- every stored source comes back oldest first; and
* the chunk lookup -- the chunks of the named sources, in the order the ids
  were given, with an id the library does not hold skipped rather than
  refused.

What stays in Python, and why:

* **The stored source model.** ``StoredSource`` is the Python dataclass the
  HTTP API answers with, and its summary is what the client reads. The tier
  holds the same fields; this module is what turns one into the other.
* **The constructor.** ``StoredSource.from_source`` assembles a stored entry
  from an ingested source and its chunks. That is a constructor, not a rule:
  it decides nothing, so there is nothing for the tier to own.
"""

from __future__ import annotations

import builtins
import logging
from collections.abc import Callable, Iterable, Mapping
from dataclasses import dataclass, field
from datetime import datetime, timezone
from typing import Any, TypeVar

from lmeditor.bridge import BridgeUnavailableError
from lmeditor.core.exceptions import LMeditorError, ValidationError
from lmeditor.core.schemas import BibliographicRecord, Source, SourceChunk
from lmeditor.core.types import SourceKind
from lmeditor.tier import server as tier_server

#: How many sources the tier keeps in its memory cache. Archived records and
#: chunks remain available after eviction or a bridge/backend restart.
#:
#: The bound that is *enforced* is the tier's: it is the tier's registry that
#: drops its oldest entry when it is full. This constant stays a Python
#: literal because a module-level constant cannot ask the tier what it is --
#: the seam is not up when this module is imported, and a constant that had to
#: wait for a subprocess would not be a constant. The two numbers are the
#: same, and the Kotlin side is the one that enforces it.
MAX_SOURCES: int = 256

logger = logging.getLogger(__name__)

_T = TypeVar("_T")


@dataclass(frozen=True)
class StoredSource:
    """One ingested source and everything derived from it."""

    source_id: str
    title: str
    kind: SourceKind
    origin: str
    chunks: tuple[SourceChunk, ...]
    record: BibliographicRecord | None = None
    byte_size: int | None = None
    omissions: tuple[str, ...] = ()
    added_at: datetime = field(default_factory=lambda: datetime.now(timezone.utc))

    @classmethod
    def from_source(
        cls,
        source: Source,
        chunks: Iterable[SourceChunk],
        *,
        record: BibliographicRecord | None = None,
        omissions: Iterable[str] = (),
    ) -> "StoredSource":
        """Build a stored entry from an ingested source and its chunks."""
        return cls(
            source_id=source.id,
            title=source.title,
            kind=source.kind,
            origin=source.origin,
            chunks=tuple(chunks),
            record=record,
            byte_size=source.byte_size,
            omissions=tuple(omissions),
        )

    def to_summary(self) -> dict[str, object]:
        """A compact description of the source for the client."""
        return {
            "source_id": self.source_id,
            "title": self.title,
            "kind": self.kind.value,
            "origin": self.origin,
            "chunk_count": len(self.chunks),
            "byte_size": self.byte_size,
            "added_at": self.added_at.isoformat(),
            "omissions": list(self.omissions),
            "bibliography": self.record.model_dump(mode="json") if self.record else None,
        }

    @classmethod
    def from_wire(cls, wire: Mapping[str, Any]) -> "StoredSource":
        """Build a stored source from the tier's wire form.

        The tier holds the stored source, so the tier's wire form is the
        authority on what a stored source is. This is where that form becomes
        the Python dataclass the rest of the backend reads.

        Raises:
            ValidationError: A field of the wire form is missing or has the
                wrong type.
        """
        return cls(
            source_id=_string_from_wire(wire, "source_id"),
            title=_string_from_wire(wire, "title"),
            kind=_kind_from_wire(wire.get("kind")),
            origin=_string_from_wire(wire, "origin"),
            chunks=_chunks_from_wire(wire.get("chunks")),
            record=_record_from_wire(wire.get("record")),
            byte_size=_optional_int_from_wire(wire.get("byte_size")),
            omissions=tuple(_string_list_from_wire(wire.get("omissions"))),
            added_at=_instant_from_wire(wire.get("added_at")),
        )

    def to_wire(self) -> dict[str, Any]:
        """The wire form of this stored source.

        The tier holds the stored source, so this is how one crosses the
        seam: every field the dataclass has, and nothing else.
        """
        return {
            "source_id": self.source_id,
            "title": self.title,
            "kind": self.kind.value,
            "origin": self.origin,
            "chunks": [chunk.model_dump(mode="json") for chunk in self.chunks],
            "record": self.record.model_dump(mode="json") if self.record else None,
            "byte_size": self.byte_size,
            "omissions": list(self.omissions),
            "added_at": _wire_timestamp(self.added_at),
        }


class SourceLibrary:
    """An archive-backed, thread-safe registry with a bounded memory cache.

    The Kotlin tier owns persistence and cache eviction. Evicted entries stay
    in the archive; existing sources are restored on demand after restart.
    This class keeps the backend API and holds no persistence rule itself.

    The registry is thread-safe, and so is the door: the seam is one pipe,
    and the bridge serialises the calls that cross it.
    """

    def __init__(self, max_sources: int = MAX_SOURCES) -> None:
        """Bind this door to the tier's registry.

        ``max_sources`` is kept for the API's sake. The bound that is
        enforced is the tier's, because the registry that would have to
        enforce it now lives there, and one registry serves the whole process.
        A caller that asks for a different bound gets the tier's.
        """
        self._max_sources = max_sources

    def add(self, stored: StoredSource) -> StoredSource:
        """Persist a source before adding it to the bounded memory cache.

        Cache eviction is the tier's and never removes archived records.
        """
        return _call(
            "store the source",
            lambda: StoredSource.from_wire(tier_server.add_source(stored.to_wire())),
        )

    def get(self, source_id: str) -> StoredSource | None:
        """The stored source with this id, if the library holds it."""
        wire = _call("read the source", lambda: tier_server.get_source(source_id))
        return StoredSource.from_wire(wire) if wire is not None else None

    def remove(self, source_id: str) -> bool:
        """Drop a source. Returns whether it was present."""
        return _call(
            "drop the source",
            lambda: tier_server.remove_source(source_id),
        )

    def list(self) -> "builtins.list[StoredSource]":
        """Every stored source, oldest first.

        The annotation names ``builtins.list`` explicitly: this method is
        called ``list``, and inside the class body that name shadows the
        builtin, so a bare ``list[...]`` would resolve to the method.
        """
        wires = _call("list the sources", tier_server.list_sources)
        return [StoredSource.from_wire(wire) for wire in wires]

    def chunks_for(self, source_ids: Iterable[str]) -> "builtins.list[SourceChunk]":
        """The chunks of the named sources, in the order the ids were given.

        Unknown ids are skipped for compatibility. Callers requiring a complete
        corpus, including notebooks, must explicitly validate source membership.
        """
        wires = _call(
            "read the chunks",
            lambda: tier_server.chunks_for(list(source_ids)),
        )
        return [SourceChunk.model_validate(wire) for wire in wires]

    def clear(self) -> None:
        """Delete all records in the selected archive. Intended for tests."""
        _call("clear the library", tier_server.clear_sources)

    def __len__(self) -> int:
        return _call("count the sources", tier_server.source_count)


#: The process-wide source library.
source_library = SourceLibrary()


__all__ = ["MAX_SOURCES", "SourceLibrary", "StoredSource", "source_library"]


